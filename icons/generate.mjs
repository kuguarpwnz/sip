// Reads icons/icons.txt and writes src/icons.gen.ts and the Kotlin IconKeys.kt from Tabler's outline SVGs.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outlineDir = join(root, "node_modules/@tabler/icons/icons/outline");
const tsOut = join(root, "src/icons.gen.ts");
const ktOut = join(root, "plugins/tauri-plugin-sip/android/src/main/java/app/sip/core/data/IconKeys.kt");
const fallbackKey = "droplet";

const names = readFileSync(join(root, "icons/icons.txt"), "utf8")
  .split("\n")
  .map((line) => line.replace(/#.*/, "").trim())
  .filter(Boolean);

const fail = (message) => {
  console.error(`icons/generate.mjs: ${message}`);
  process.exit(1);
};

const duplicates = names.filter((name, i) => names.indexOf(name) !== i);
if (duplicates.length) fail(`duplicate icon names: ${duplicates.join(", ")}`);
if (!names.includes(fallbackKey)) fail(`icons.txt must contain "${fallbackKey}", the fallback for unknown keys`);

const missing = names.filter((name) => !existsSync(join(outlineDir, `${name}.svg`)));
if (missing.length) fail(`not in @tabler/icons outline: ${missing.join(", ")}`);

const inner = (name) => {
  const svg = readFileSync(join(outlineDir, `${name}.svg`), "utf8");
  const body = svg.slice(svg.indexOf(">") + 1, svg.lastIndexOf("</svg>"));
  return body
    .replace(/<path stroke="none"[^>]*\/>/, "")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
};

const group = (name) =>
  `<g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner(name)}</g>`;

const ts = `// Generated by icons/generate.mjs from icons/icons.txt. Do not edit.
export const ICON_KEYS = [
${names.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
] as const;

export type IconKey = (typeof ICON_KEYS)[number];

export const ICONS: Record<IconKey, string> = {
${names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(group(n))},`).join("\n")}
};
`;

const kt = `// Generated by icons/generate.mjs from icons/icons.txt. Do not edit.
package app.sip.core.data

object IconKeys {
    const val FALLBACK = "${fallbackKey}"

    val ALL: Set<String> = linkedSetOf(
${names.map((n) => `        "${n}",`).join("\n")}
    )
}
`;

writeFileSync(tsOut, ts);
writeFileSync(ktOut, kt);
console.log(`${names.length} icons -> ${tsOut.replace(root + "/", "")}, ${ktOut.replace(root + "/", "")}`);
